$post_data = array(
	'post_title'   => $title,
	'post_content' => $content,
	'post_status'  => 'publish',
	'post_author'  => 1,
	'post_type'    => 'post',
);

$post_id = wp_insert_post( $post_data, true );

if ( is_wp_error( $post_id ) ) {
	echo 'Ошибка: ' . $post_id->get_error_message() . "\n";
	exit( 1 );
}

$stati_term = get_term_by( 'slug', 'stati', 'category' );
if ( $stati_term ) {
	wp_set_post_categories( $post_id, array( $stati_term->term_id ) );
}

wp_set_post_tags( $post_id, array(
	'Anthropic',
	'Пентагон',
	'Искусственный интеллект',
	'Этика ИИ',
	'Политика',
), false );

echo "Статья создана (ID: {$post_id})\n";
echo 'URL: ' . get_permalink( $post_id ) . "\n";
