<?php
/**
 * Создание статьи о конфликте Anthropic и Пентагона.
 * Запускать один раз: php create-anthropic-article.php
 */

if ( php_sapi_name() !== 'cli' ) {
	die( 'Только из командной строки.' );
}

require_once __DIR__ . '/wp-load.php';

$title = 'Конфликт Anthropic и Пентагона достиг пика';

$existing = get_page_by_title( $title, OBJECT, 'post' );
if ( $existing ) {
	echo "Статья «{$title}» уже существует (ID: {$existing->ID})\n";
	echo 'URL: ' . get_permalink( $existing->ID ) . "\n";
	exit( 0 );
}

$content = <<<'HTML'
<p><strong>Подробный рассказ о споре между компанией «Антропик» и Министерством обороны Соединённых Штатов</strong></p>
<p><em>(по состоянию на двадцать восьмое февраля две тысячи двадцать шестого года)</em></p>

<p>Это один из самых громких и принципиальных конфликтов за всю историю отношений крупных технологических фирм и правительства Америки. Спор достиг высшей точки двадцать седьмого февраля две тысячи двадцать шестого года, когда истёк срок ультиматума военного ведомства и администрация президента применила жёсткие меры против компании.</p>

<h2>Как всё начиналось</h2>

<p>В июле две тысячи двадцать пятого года компания «Антропик» получила крупный договор на двести миллионов долларов от военного ведомства. Она стала первой среди лабораторий передового искусственного интеллекта, которая разместила свою главную модель под названием «Клод» в полностью секретных компьютерных сетях Министерства обороны и национальных исследовательских центров.</p>

<p>Модель активно помогала в анализе разведывательных данных, создании моделей будущих событий, киберзащите, планировании операций и других военных задачах.</p>

<p>Компания всегда подчёркивала свой патриотизм: она отказывалась от сотен миллионов долларов прибыли от заказчиков из Китая, блокировала попытки атак из этой страны и активно поддерживала строгий контроль за вывозом важнейших микросхем.</p>

<h2>В чём суть спора</h2>

<p>С самого начала в договоре были записаны два строгих запрета, которые нельзя нарушать ни при каких условиях:</p>

<blockquote>
<h3>Массовое внутреннее наблюдение за обычными американскими гражданами</h3>
<p>«Применение искусственного интеллекта для тотальной слежки за людьми внутри страны несёт серьёзные новые угрозы основным свободам и правам человека. Это несовместимо с принципами демократии».</p>
</blockquote>

<blockquote>
<h3>Полностью автономное смертоносное оружие</h3>
<p>«Сегодняшние самые мощные модели ещё недостаточно надёжны. Мы не можем сознательно поставлять продукт, который может подвергнуть опасности как американских военных, так и мирных жителей».</p>
</blockquote>

<p>Военное ведомство (при новом министре обороны Пите Хегсете) потребовало полностью убрать эти два запрета и разрешить использовать модель «Клод» для любых законных военных целей без исключений. Официально они заявили, что сами не планируют ни массовую слежку внутри страны, ни полностью автономное оружие, но настаивали на полной свободе без каких-либо ограничений со стороны компании.</p>

<h2>Как развивались события в последние дни</h2>

<p>Во вторник прошла личная встреча министра обороны Пита Хегсета и главного руководителя компании «Антропик» Дарио Амадеи прямо в здании военного ведомства. Министр вручил жёсткий ультиматум: до семнадцати часов одной минуты по вашингтонскому времени в пятницу двадцать седьмого февраля все запреты должны быть сняты. Иначе договор будет расторгнут, а компания получит статус «угрозы для цепочки поставок национальной безопасности» и может быть применён специальный закон о принудительном производстве.</p>

<p>Двадцать шестого и двадцать седьмого февраля Дарио Амадеи опубликовал большое открытое обращение на официальном сайте компании. Главные слова в нём:</p>

<blockquote><p>«Мы не можем с чистой совестью согласиться на это требование».</p></blockquote>

<blockquote><p>«Эти две угрозы противоречат друг другу: одна объявляет нас опасностью для безопасности, а другая говорит, что наша модель жизненно важна для обороны страны».</p></blockquote>

<p>Вечером двадцать седьмого февраля, после истечения срока:</p>

<ul>
<li>Президент Дональд Трамп распорядился, чтобы все государственные учреждения немедленно прекратили использовать любые технологии компании «Антропик». Для военного ведомства установлен срок плавного отказа в течение шести месяцев.</li>
<li>Министр Хегсет официально объявил компанию «угрозой для цепочки поставок национальной безопасности» (такое обозначение раньше давали только фирмам из враждебных стран). Из-за этого даже частные военные подрядчики обязаны прекратить с ней работу.</li>
<li>Один из заместителей министра назвал Дарио Амадеи «человеком с комплексом бога, который хочет лично управлять армией страны».</li>
</ul>

<p>Двадцать восьмого февраля Дарио Амадеи дал большое интервью главной телевизионной компании страны. Он назвал действия военного ведомства ответными и наказательными. Компания подтвердила, что готова судиться: «У министра нет права запрещать всем подрядчикам работать с нами за пределами государственных договоров».</p>

<h2>Что происходит сейчас</h2>

<p>Компания «Антропик» уже подала заявление, что будет оспаривать это решение в суде. Она готова обеспечить плавный переход на другие системы в течение шести месяцев и продолжает предлагать своё сотрудничество, но только при сохранении двух главных запретов.</p>

<p>Многие в технологической отрасли и в обществе поддерживают позицию компании, считая её принципиальной и честной.</p>

<p>Это первый случай, когда американскую фирму, создающую искусственный интеллект, публично наказали именно за то, что она установила этические границы использования своей технологии в армии. Многие считают, что сейчас решается главный вопрос: <strong>кто в итоге будет определять границы применения искусственного интеллекта в военных делах — правительство или сами создатели моделей</strong>.</p>
