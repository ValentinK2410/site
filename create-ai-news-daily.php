<?php
/**
 * Создание статьи: ИИ-новости за сутки.
 * Запускать один раз: php create-ai-news-daily.php
 */

if ( php_sapi_name() !== 'cli' ) {
	die( 'Только из командной строки.' );
}

require_once __DIR__ . '/wp-load.php';

global $wpdb;

$title = 'ИИ-новости за сутки: Китай бьёт по рукам Америке + ШОК в школе!';

$existing_id = $wpdb->get_var( $wpdb->prepare(
	"SELECT ID FROM {$wpdb->posts} WHERE post_type = 'post' AND post_title = %s AND post_status != 'trash' LIMIT 1",
	$title
) );
if ( $existing_id ) {
	echo "Статья «{$title}» уже существует (ID: {$existing_id})\n";
	echo 'URL: ' . get_permalink( $existing_id ) . "\n";
	exit( 0 );
}

$content = <<<'HTML'
<h2>Главный удар дня: DeepSeek V4 рвёт шаблон</h2>

<p>Китайская компания DeepSeek (те самые, кто делает супермощные модели за копейки) впервые в истории <strong>отказала Nvidia и AMD в доступе</strong> к своей новой флагманской модели V4.</p>

<p><strong>Приоритет — только китайским чипам Huawei.</strong></p>

<p>Модель вот-вот выйдет, и теперь ИИ-мир официально раскалывается на два лагеря: американский и китайский. Оптимизировать под чужое железо больше не будут. Это не просто новость — это сигнал: <strong>гонка стала жёстче, чем когда-либо</strong>.</p>

<h2>Anthropic усиливает агентов</h2>

<p>Anthropic (создатели Claude) тихо купила стартап <strong>Vercept</strong>. Теперь их ИИ-агенты (программы, которые сами управляют компьютером как человек: кликают, печатают, решают задачи) станут ещё умнее и опаснее для рутины.</p>

<h2>Nvidia снова бьёт рекорды</h2>

<p>Выручка взлетела — пузырь ИИ пока не лопается, акции растут.</p>

<h2>Samsung Galaxy S26</h2>

<p>Новый флагман с <strong>Galaxy AI</strong> прямо на телефоне: понимает контекст, предугадывает, что тебе нужно, и почти ничего не отправляет в облако. Приватность на максимуме.</p>

<h2>А теперь — настоящий ВЗРЫВ в школе</h2>

<p><em>(декабрь 2025, но скандал взорвался именно сейчас)</em></p>

<p>В обычной начальной школе <strong>Delevan Drive Elementary</strong> в Лос-Анджелесе (4-й класс, дети 9–10 лет) учитель дал домашку: прочитать про Пеппи Длинныйчулок и сделать обложку книги.</p>

<p>Девочка зашла в бесплатный школьный инструмент <strong>Adobe Express for Education</strong> (это графический редактор с встроенным генеративным ИИ — он рисует картинки по текстовому запросу, который называется промпт).</p>

<p>Она написала нормальный детский промпт: <em>«рыжеволосая девочка с косичками торчащими в стороны и в длинных чулках»</em>.</p>

<p>А ИИ выдал… <strong>сексуализированные фото взрослых женщин в нижнем белье и бикини</strong>.</p>

<p>Мама <strong>Jody Hughes</strong> увидела, подняла тревогу. Другие родители на тех же школьных ноутбуках Chromebook легко повторили то же самое.</p>

<p>Родительская группа <strong>Schools Beyond Screens</strong> уже вышла в школьный совет с требованием: <strong>запретить Adobe в школах навсегда</strong>.</p>

<p>Именно на фоне этого <strong>Калифорния срочно выпустила новые жёсткие правила безопасности ИИ в образовании</strong>. Теперь школы обязаны проверять инструменты, чтобы такое больше никогда не повторилось.</p>

<h2>Итог</h2>

<p>Вчерашние сутки показали две стороны одной медали — <strong>ИИ становится мощнее и одновременно опаснее</strong>. Китай закрывает дверь, а в школах уже видны первые жертвы. Следим дальше.</p>

<p><em>Источники: Reuters, TechCrunch, CalMatters, LAist — всё от 25–27 февраля 2026.</em></p>
HTML;

$post_id = wp_insert_post( [
	'post_title'   => $title,
	'post_content' => $content,
	'post_status'  => 'publish',
	'post_author'  => 1,
	'post_type'    => 'post',
], true );

if ( is_wp_error( $post_id ) ) {
	echo "Ошибка: " . $post_id->get_error_message() . "\n";
	exit( 1 );
}

$cat = get_cat_ID( 'Новости' );
if ( ! $cat ) {
	$cat = wp_create_category( 'Новости' );
}
wp_set_post_categories( $post_id, [ $cat ] );

echo "Статья создана (ID: {$post_id})\n";
echo 'URL: ' . get_permalink( $post_id ) . "\n";
